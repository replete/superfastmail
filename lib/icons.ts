/** Fill every `<button data-icon="name">` with its icon. */
export function applyIcons(root: ParentNode = document) {
  for (const el of root.querySelectorAll<HTMLElement>('[data-icon]')) {
    const icon = ICONS[el.dataset.icon as keyof typeof ICONS];
    if (icon) insert(el, 'afterbegin', icon);
  }
}
